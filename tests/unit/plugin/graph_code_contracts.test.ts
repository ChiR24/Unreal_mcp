// manage_blueprint read_graph_as_code and write_graph_from_code: a Blueprint's graphs as the text of Epic's UE 5.8
// Blueprint DSL, and that text written back as nodes (plugin Domains/BlueprintGraph/Code). Wiring, read-only and
// all-or-nothing contracts; the decompiler's known answers run in the editor (EngineWire.BlueprintGraph.Code.*) and live.

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

const PRIVATE = join('plugins', 'EngineWire', 'Source', 'EngineWire', 'Private');
const CODE = join(PRIVATE, 'Domains', 'BlueprintGraph', 'Code');

/** Line comments removed, CRLF normalized, so no assertion can be satisfied by prose. */
const code = (path: string): string => readFileSync(path, 'utf8').replace(/\r\n/gu, '\n').replace(/\/\/[^\n]*/gu, ' ');

describe('read_graph_as_code', () => {
  it('is routed to the graph handler as a read, needing a graph only when it names one', () => {
    expect(code(join(PRIVATE, 'Core', 'Subsystem', 'EngineWireSubsystemHandlerRegistration.cpp'))).toContain('TEXT("read_graph_as_code")');
    const graph = code(join(PRIVATE, 'Domains', 'BlueprintGraph', 'McpBPGraphHandlers.cpp'));
    expect(graph).toMatch(/bCode \? Payload->HasField\(TEXT\("graphName"\)\)/u);
    expect(graph).toMatch(/Context\.bDeferCompile = true;\s*return bLint \? McpBPLint::HandleLint\(Context\) : McpGraphCode::HandleReadGraphAsCode\(Context\) \|\| McpGraphCode::HandleWriteGraphFromCode\(Context\);/u);
  });

  it('changes nothing: no node made or removed, no Modify, compile, save or transaction', () => {
    for (const file of readdirSync(CODE).filter((name) => !name.includes('Tests') && !name.startsWith('McpGraphCodeWrite'))) {
      const text = code(join(CODE, file));
      for (const forbidden of ['Modify(', 'CreateNode', 'SpawnNode', 'AddNode', 'RemoveNode', 'DestroyNode', 'NewObject', 'MarkBlueprintAsModified', 'CompileBlueprint', 'McpSafeAssetSave', 'FScopedTransaction']) {
        expect(text, `${file} must not call ${forbidden}`).not.toContain(forbidden);
      }
    }
  });

  it('takes a trailing default from the pin itself, never from a node made to read it', () => {
    expect(code(join(CODE, 'McpGraphCodeSnapshot.cpp'))).toContain('Pin->DoesDefaultValueMatchAutogenerated()');
  });

  it('knows control flow by node class, and loops by their StandardMacros graph', () => {
    const snapshot = code(join(CODE, 'McpGraphCodeSnapshot.cpp'));
    for (const node of ['UK2Node_IfThenElse', 'UK2Node_Switch', 'UK2Node_Select', 'UK2Node_Knot', 'UK2Node_FunctionResult']) {
      expect(snapshot).toContain(`${node}::StaticClass()`);
    }
    expect(snapshot).toContain('/Engine/EditorBlueprintResources/StandardMacros');
  });

  it('says where a path runs into a node already printed instead of dropping it', () => {
    const stmts = code(join(CODE, 'McpGraphCodeStmts.cpp'));
    expect(stmts).toMatch(/if \(Visited\.Contains\(Index\)\)\s*\{\s*Goto\(At, State\);\s*return;/u);
  });

  it('with entry, keeps that form alone and lists only what it runs and the values those read', () => {
    const read = code(join(CODE, 'McpGraphCodeRead.cpp'));
    expect(read).toMatch(/Text = KeepEntry\(Text, Entries, Heads, OutNames\);\s*if \(Text\.IsEmpty\(\)\)\s*\{\s*return INDEX_NONE;/u);
    expect(read).toMatch(/Heads\.Contains\(Read\.Nodes\[At\]\.Id\)\)\s*\{\s*Shown\.Append\(Write::WritePlanParts::Reach\(Read, At\)\);/u);
    expect(read).toMatch(/TryGetStringField\(TEXT\("entry"\), Entry\)[\s\S]*ReadAsCode\(Blueprint, Graphs, Entries, bCodeOnly, \*Result, Names\);[\s\S]*TEXT\("ENTRY_NOT_FOUND"\)/u);
  });

  it('with codeOnly, leaves the node and link lists out and keeps their counts', () => {
    const read = code(join(CODE, 'McpGraphCodeRead.cpp'));
    expect(read).toContain('Context.Payload->TryGetBoolField(TEXT("codeOnly"), bCodeOnly);');
    expect(read).toMatch(/if \(!bCodeOnly\)\s*\{\s*Result\.SetArrayField\(TEXT\("nodes"\), NodeRows\);\s*Result\.SetArrayField\(TEXT\("links"\), LinkRows\);/u);
    expect(read.indexOf('Result.SetNumberField(TEXT("nodeCount")')).toBeLessThan(read.indexOf('if (!bCodeOnly)\n'));
    expect(code(join(CODE, 'McpGraphCodeWriteHandler.cpp'))).toContain('ReadAsCode(Blueprint, Graphs, Written, false, *Read, Names);');
  });
});

describe('write_graph_from_code', () => {
  const handler = code(join(CODE, 'McpGraphCodeWriteHandler.cpp'));
  const order = (...needles: string[]): void => {
    let from = 0;
    for (const needle of needles) {
      const at = handler.indexOf(needle, from);
      expect(at, `${needle} after the previous step`).toBeGreaterThanOrEqual(0);
      from = at + needle.length;
    }
  };

  it('is routed to the graph handler', () => {
    expect(code(join(PRIVATE, 'Core', 'Subsystem', 'EngineWireSubsystemHandlerRegistration.cpp'))).toContain('TEXT("write_graph_from_code")');
  });

  it('refuses during Play and checks every form before the Blueprint is touched', () => {
    order('IsPlaySessionInProgress()', 'ParseSExpr(', 'RouteForms(', 'PlanGraph(', 'TakeSnapshot(Blueprint)', 'BuildForms(');
  });

  it('keeps the old body out of the compile and removes it only once the new code compiles', () => {
    order('Plan.Graph->RemoveNode(Node)', 'McpCompileBlueprintWithDiagnostics(', 'Plan.Graph->AddNode(Node, false, false)',
      'if (!bCompiled && Before.bCompiled)', 'Rollback(Blueprint, Before)', 'FBlueprintEditorUtils::RemoveNode(Blueprint, Node');
  });

  it('never keeps a pointer into the array DataPins returns (it dies with the statement)', () => {
    for (const file of readdirSync(CODE).filter((name) => name.startsWith('McpGraphCodeWrite'))) {
      expect(code(join(CODE, file)), file).not.toMatch(/DataPins\([^;]*\)\s*\.\s*(FindByPredicate|Find|GetData)\(/u);
    }
  });

  it('reads back only the entries it wrote, through the reader read_graph_as_code reads one entry with', () => {
    expect(handler).toMatch(/Written\.Add\(EntryName\(TypeIdOf\(Node\)\)\);[\s\S]*ReadAsCode\(Blueprint, Graphs, Written, false, \*Read, Names\);/u);
    expect(handler).not.toContain('Decompile(');
    expect(code(join(CODE, 'McpGraphCodeWriteForm.cpp'))).toContain('Plan.Entries = Entries;');
  });

  it('puts the Blueprint back on every refusal after the snapshot', () => {
    expect(handler.match(/Rollback\(Blueprint, Before\);/gu)).toHaveLength(2);
    expect(handler).toContain('McpBlueprintBehaviour::UndoBatch(');
  });

  it('makes a value only from a node that gives one, preferring a menu entry with a result under a shared id', () => {
    const expr = code(join(CODE, 'McpGraphCodeWriteExpr.cpp'));
    expect(expr).toContain('CallNode(Value, Bindings, Flow, {}, true)');
    expect(expr).toMatch(/return Node && !Out \? Fail\(/u);
    const catalog = code(join(CODE, 'McpGraphCodeCatalog.cpp'));
    expect(catalog).toMatch(/Function->GetReturnProperty\(\) \|\| Function->HasAnyFunctionFlags\(FUNC_HasOutParms\)/u);
    expect(catalog).toMatch(/Entry\.Id\.Equals\(TypeId, Case\) && \(!bValue \|\| GivesValue\(Entry\)\)/u);
    expect(code(join(CODE, 'McpGraphCodeWriteNodes.cpp'))).toContain('FindMenuEntry(Menu, TypeId, bValue)');
  });

  it('types % and string compares by their operands, and refuses an object path that loads nothing', () => {
    const values = code(join(CODE, 'McpGraphCodeWriteValues.cpp'));
    expect(values).toContain('TEXT("Math|Float|%(Float)")');
    expect(values).toContain('TEXT("Utilities|String|EqualExactly(String)")');
    expect(values).toMatch(/if \(bObject && !Pin->DefaultObject && !Trimmed\.IsEmpty\(\)/u);
    expect(code(join(CODE, 'McpGraphCodeWriteExpr.cpp'))).not.toContain('Utilities|Operators|Modulo');
    expect(code(join(CODE, 'McpGraphCodeWriteOps.cpp'))).toMatch(/TypedOperator\(Op, OperandCategory\(Call\.Items\[1\], Pre\[0\], Bindings\)/u);
  });
});

describe('read -> write round trips', () => {
  it('calls a custom event the same code makes: every entry first, then the skeleton and the menu again, then the bodies', () => {
    const form = code(join(CODE, 'McpGraphCodeWriteForm.cpp'));
    const build = form.slice(form.indexOf('bool BuildForms('));
    expect(build).toMatch(/Entries\.Add\(Transpiler\.Entry\([\s\S]*!Plan\.Entries\[At\] && Entries\.Last\(\)->IsA<UK2Node_CustomEvent>\(\)/u);
    expect(build).toMatch(/if \(bNewEvent\)\s*\{\s*FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified\(Blueprint\);\s*Candidates = MenuCandidates\(Titles\);\s*Transpiler\.Menu = MenuEntries\(/u);
    expect(build.indexOf('MarkBlueprintAsStructurallyModified')).toBeLessThan(build.indexOf('Transpiler.Body('));
    // The event graph's plan is built first, so a function written in the same code finds the event's call too.
    expect(code(join(CODE, 'McpGraphCodeWriteHandler.cpp'))).toContain('&Plans.InsertDefaulted_GetRef(0)');
  });

  it('prints a node by the title of the menu entry that makes it, so the menu id it gets makes it back', () => {
    const snapshot = code(join(CODE, 'McpGraphCodeSnapshot.cpp'));
    // A variable's node: the title of its owner's spawner for that property and node class (Set Show Mouse Cursor).
    expect(snapshot).toMatch(/Spawner->NodeClass\.Get\(\) == Node->GetClass\(\)[\s\S]*GetAssociatedProperty\(\)[\s\S]*Field->GetFName\(\) == Property->GetFName\(\)[\s\S]*return Spawner->PrimeDefaultUiSpec\(\)\.MenuName\.ToString\(\);/u);
    // A node made from a class: its menu title (Spawn Actor from Class), not the list title that names the class.
    expect(snapshot).toContain('Node->IsA<UK2Node_ConstructObjectFromClass>() ? ENodeTitleType::MenuTitle : ENodeTitleType::ListView');
    expect(snapshot).toContain('const FString Title = WithoutWhitespace(MenuTitleOf(Node));');
  });

  it('quotes an object or class reference, so one that holds none reads as "" and not as the 0 the writer refuses', () => {
    const snapshot = code(join(CODE, 'McpGraphCodeSnapshot.cpp'));
    for (const category of ['PC_Object', 'PC_Class', 'PC_Interface', 'PC_SoftObject', 'PC_SoftClass']) {
      expect(snapshot).toContain(`UEdGraphSchema_K2::${category}`);
    }
    expect(snapshot).toContain('Item.bText = !Type.IsContainer() && MakeArrayView(Quoted).Contains(Type.PinCategory);');
  });

  it('fills a call\'s inputs read again for each argument, so a class set first adds the pins the rest fill', () => {
    const fill = code(join(CODE, 'McpGraphCodeWriteValues.cpp'));
    expect(fill).toMatch(/for \(int32 At = 0; At < Args\.Num\(\);\)\s*\{\s*const TArray<UEdGraphPin\*> Ins = DataPins\(Node, true\);/u);
    expect(fill).toMatch(/if \(!Pin && Pass == 0\)\s*\{\s*\+\+At;\s*continue;/u);
    const expr = code(join(CODE, 'McpGraphCodeWriteExpr.cpp'));
    expect(expr).toContain('if (!Fill(Node, TypeId, Args, Bindings, Flow))');
    expect(expr).not.toContain('DataPins(Node, true)');
  });

  it('leaves the target of a call on the Blueprint itself unwired: the reader drops it, the writer skips it', () => {
    const snapshot = code(join(CODE, 'McpGraphCodeSnapshot.cpp'));
    expect(snapshot).toContain('Item.bSelfTarget = IsSelfTarget(Blueprint, Pin);');
    expect(snapshot).toMatch(/PinSubCategory == UEdGraphSchema_K2::PSC_Self \|\| \(Self && Target && \(Self->IsChildOf\(Target\) \|\| Self->ImplementsInterface\(Target\)\)\)/u);
    const expr = code(join(CODE, 'McpGraphCodeExpr.cpp'));
    expect(expr).toMatch(/if \(Ins\.Num\(\) > 0 && Ins\[0\]->bSelfTarget && Ins\[0\]->Links\.Num\(\) == 0 && Ins\[0\]->Value\.IsEmpty\(\)\)\s*\{\s*Ins\.RemoveAt\(0\);/u);
    // A target kept (wired or set) keeps every argument after it, so the writer sees one for every input.
    expect(expr).toMatch(/const int32 Keep = Ins\.Num\(\) > 0 && Ins\[0\]->bSelfTarget \? Ins\.Num\(\) : 1;\s*while \(Args\.Num\(\) > Keep/u);
    expect(code(join(CODE, 'McpGraphCodeWriteValues.cpp'))).toMatch(/const int32 Skipped = First\.Num\(\) > 0 && Positional < First\.Num\(\) && IsSelfTarget\(Blueprint, First\[0\]\) \? 1 : 0;\s*int32 Next = Skipped;/u);
    expect(code(join(CODE, 'McpGraphCodeSelfCallTests.cpp'))).toContain('"EngineWire.BlueprintGraph.Code.SelfCall"');
  });

  it('names the ids whose title starts with an unknown one when none has its title, in both refusals', () => {
    const catalog = code(join(CODE, 'McpGraphCodeCatalog.cpp'));
    expect(catalog).toMatch(/if \(!Key\.IsEmpty\(\) && !Ids\.ContainsByPredicate[\s\S]*MenuEntries\(Blueprint, Graph, MenuCandidates\(Prefix, true\), Prefix, true\)/u);
    expect(catalog).toMatch(/const TArray<FString> Offered = OfferedIds\(Blueprint, Graph, Entries, MenuId\);/u);
    expect(code(join(CODE, 'McpGraphCodeWriteNodes.cpp'))).toContain('const TArray<FString> Offered = OfferedIds(Blueprint, Graph, Menu, TypeId);');
  });
});
