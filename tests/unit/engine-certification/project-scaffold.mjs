// @ts-check
// tests/unit/engine-certification/project-scaffold.mjs
// Task 52 — the smallest real C++ UE project that can host a certification.
//
// It has to be a C++ project, because a Blueprint-only project never compiles the
// bridge plugin and so proves nothing about whether the plugin builds against
// THIS engine. It has to be generated rather than copied, because copying a
// project carries its DerivedDataCache, its Saved state and its previously-built
// binaries — and "never reuse binaries across minors" is precisely the rule a
// copied project breaks silently.
//
// Everything below is a pure string function of the engine version and the
// allocated ports, so the parts that vary by engine are testable with no engine
// present. The two that actually vary:
//
//   EngineIncludeOrderVersion exists from 5.1. Emitting it on 5.0 is a C# compile
//   error inside UBT, which surfaces as an opaque "target rules failed to
//   compile" a long way from its cause.
//
//   The settings block is written to DefaultGame.ini because the plugin's
//   UMcpAutomationBridgeSettings is `config=Game`. Writing it to DefaultEngine.ini
//   parses fine and is silently ignored, which looks exactly like the plugin
//   failing to start.

/** @typedef {{ major: number, minor: number, patch: number }} Version */

/** @param {string} name */
export function uprojectFile(name) {
  return `${JSON.stringify({
    FileVersion: 3,
    EngineAssociation: '',
    Category: '',
    Description: 'Task 52 disposable certification project. Generated; safe to delete.',
    Modules: [{ Name: name, Type: 'Runtime', LoadingPhase: 'Default' }],
    Plugins: [{ Name: 'McpAutomationBridge', Enabled: true }],
  }, null, 2)}\n`;
}

/**
 * A target rules file. `IncludeOrderVersion` is emitted only where the enum
 * exists, which is the one line that genuinely differs across the supported span.
 * @param {{ name: string, kind: 'Game'|'Editor', engine: Version }} spec
 */
export function targetFile(spec) {
  const className = spec.kind === 'Editor' ? `${spec.name}EditorTarget` : `${spec.name}Target`;
  const includeOrder = spec.engine.major > 5 || (spec.engine.major === 5 && spec.engine.minor >= 1)
    ? '\t\tIncludeOrderVersion = EngineIncludeOrderVersion.Latest;\n'
    : '';
  return [
    '// Generated by Task 52 certification orchestration. Do not edit.',
    'using UnrealBuildTool;',
    '',
    `public class ${className} : TargetRules`,
    '{',
    `\tpublic ${className}(TargetInfo Target) : base(Target)`,
    '\t{',
    `\t\tType = TargetType.${spec.kind};`,
    '\t\tDefaultBuildSettings = BuildSettingsVersion.Latest;',
    includeOrder.replace(/\n$/u, ''),
    `\t\tExtraModuleNames.Add("${spec.name}");`,
    '\t}',
    '}',
    '',
  ].filter((line) => line.length > 0 || true).join('\n');
}

/** @param {string} name */
export function moduleBuildFile(name) {
  return [
    '// Generated by Task 52 certification orchestration. Do not edit.',
    'using UnrealBuildTool;',
    '',
    `public class ${name} : ModuleRules`,
    '{',
    `\tpublic ${name}(ReadOnlyTargetRules Target) : base(Target)`,
    '\t{',
    '\t\tPCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;',
    '\t\tPublicDependencyModuleNames.AddRange(new string[] { "Core", "CoreUObject", "Engine", "InputCore" });',
    '\t}',
    '}',
    '',
  ].join('\n');
}

/** @param {string} name */
export function moduleSourceFile(name) {
  return [
    '// Generated by Task 52 certification orchestration. Do not edit.',
    '#include "Modules/ModuleManager.h"',
    '',
    `IMPLEMENT_PRIMARY_GAME_MODULE(FDefaultGameModuleImpl, ${name}, "${name}");`,
    '',
  ].join('\n');
}

/**
 * The plugin's own settings, in the file the plugin actually reads.
 *
 * Loopback only and no capability token: this project is disposable, reachable
 * only from this host, and a token in a generated config file on disk would be a
 * credential written by a test. The non-loopback flags are pinned to False rather
 * than omitted, so a future default flip cannot quietly expose a run to the LAN.
 * @param {{ nativePort: number, wsPorts: readonly number[] }} spec
 */
export function defaultGameIni(spec) {
  return [
    '; Generated by Task 52 certification orchestration. Do not edit.',
    '[/Script/McpAutomationBridge.McpAutomationBridgeSettings]',
    'bAlwaysListen=True',
    'ListenHost=127.0.0.1',
    `ListenPorts=${spec.wsPorts.join(',')}`,
    'bRequireCapabilityToken=False',
    'bAllowNonLoopback=False',
    'bEnableNativeMCP=True',
    `NativeMCPPort=${spec.nativePort}`,
    '',
  ].join('\n');
}

/** Minimal engine config: no rendering, no audio, nothing that needs a display. */
export function defaultEngineIni() {
  return [
    '; Generated by Task 52 certification orchestration. Do not edit.',
    '[/Script/EngineSettings.GameMapsSettings]',
    'EditorStartupMap=/Engine/Maps/Templates/Template_Default.Template_Default',
    '',
    '[/Script/Engine.Engine]',
    '!ActiveGameNameRedirects=ClearArray',
    '',
  ].join('\n');
}

/**
 * Every generated file, as { relativePath: contents }. Returned as data so the
 * caller writes them through its own ownership guard rather than this module
 * touching the filesystem.
 * @param {{ name: string, engine: Version, nativePort: number, wsPorts: readonly number[] }} spec
 */
export function scaffoldFiles(spec) {
  return {
    [`${spec.name}.uproject`]: uprojectFile(spec.name),
    [`Source/${spec.name}.Target.cs`]: targetFile({ name: spec.name, kind: 'Game', engine: spec.engine }),
    [`Source/${spec.name}Editor.Target.cs`]: targetFile({ name: spec.name, kind: 'Editor', engine: spec.engine }),
    [`Source/${spec.name}/${spec.name}.Build.cs`]: moduleBuildFile(spec.name),
    [`Source/${spec.name}/${spec.name}.cpp`]: moduleSourceFile(spec.name),
    'Config/DefaultEngine.ini': defaultEngineIni(),
    'Config/DefaultGame.ini': defaultGameIni({ nativePort: spec.nativePort, wsPorts: spec.wsPorts }),
  };
}
